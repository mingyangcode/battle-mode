export function displayError(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error);
  if (message in copy) return copy[message as keyof typeof copy];
  return /[\u3400-\u9fff]/.test(message) && !/[a-z]{3,}/i.test(message)
    ? message
    : labels.unknownError;
}
export function analysisWarning(message: string): string {
  return message.includes("Round Duration")
    ? "可用的不同片段较少，可缩短每人时长或手动设置舞者 A、B 的片段。"
    : /[a-z]{3,}/i.test(message)
      ? labels.analysisWarning
      : message;
}

